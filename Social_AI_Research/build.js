const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const ENV = path.join(ROOT, '.env');

function loadEnv() {
  if (!fs.existsSync(ENV)) {
    console.warn('No .env file found — using defaults. Copy .env.example to .env to override.');
    return {};
  }
  const env = {};
  for (const raw of fs.readFileSync(ENV, 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  }
  return env;
}

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dst, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

function main() {
  const env = loadEnv();
  const backendUrl = (env.BACKEND_URL || 'http://127.0.0.1:8765').replace(/\/+$/, '');

  if (fs.existsSync(DIST)) fs.rmSync(DIST, { recursive: true, force: true });
  copyDir(SRC, DIST);

  const config = `// AUTO-GENERATED by build.js — do not commit. Regenerate by editing .env and running \`npm run build\`.\nself.SAIR_CONFIG = ${JSON.stringify({ backendUrl })};\n`;
  fs.writeFileSync(path.join(DIST, 'config.js'), config);

  console.log('Built dist/.');
  console.log(`  backendUrl: ${backendUrl}`);
  console.log('Now reload the extension in chrome://extensions. If host_permissions');
  console.log('changed (e.g., backend URL host differs from previous build), you may');
  console.log('need to remove and re-add the unpacked extension.');
}

main();
